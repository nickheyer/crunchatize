use minifb::Key;

// DirectInput scan code for a window key, 0 when the game never reads that key
pub fn scan_code(key: Key) -> usize {
    match key {
        Key::Escape => 0x01,
        Key::Key1 => 0x02,
        Key::Key2 => 0x03,
        Key::Key3 => 0x04,
        Key::Key4 => 0x05,
        Key::Key5 => 0x06,
        Key::Key6 => 0x07,
        Key::Key7 => 0x08,
        Key::Key8 => 0x09,
        Key::Key9 => 0x0a,
        Key::Key0 => 0x0b,
        Key::Minus => 0x0c,
        Key::Equal => 0x0d,
        Key::Backspace => 0x0e,
        Key::Tab => 0x0f,
        Key::Q => 0x10,
        Key::W => 0x11,
        Key::E => 0x12,
        Key::R => 0x13,
        Key::T => 0x14,
        Key::Y => 0x15,
        Key::U => 0x16,
        Key::I => 0x17,
        Key::O => 0x18,
        Key::P => 0x19,
        Key::LeftBracket => 0x1a,
        Key::RightBracket => 0x1b,
        Key::Enter => 0x1c,
        Key::LeftCtrl => 0x1d,
        Key::A => 0x1e,
        Key::S => 0x1f,
        Key::D => 0x20,
        Key::F => 0x21,
        Key::G => 0x22,
        Key::H => 0x23,
        Key::J => 0x24,
        Key::K => 0x25,
        Key::L => 0x26,
        Key::Semicolon => 0x27,
        Key::Apostrophe => 0x28,
        Key::Backquote => 0x29,
        Key::LeftShift => 0x2a,
        Key::Backslash => 0x2b,
        Key::Z => 0x2c,
        Key::X => 0x2d,
        Key::C => 0x2e,
        Key::V => 0x2f,
        Key::B => 0x30,
        Key::N => 0x31,
        Key::M => 0x32,
        Key::Comma => 0x33,
        Key::Period => 0x34,
        Key::Slash => 0x35,
        Key::RightShift => 0x36,
        Key::NumPadAsterisk => 0x37,
        Key::LeftAlt => 0x38,
        Key::Space => 0x39,
        Key::CapsLock => 0x3a,
        Key::F1 => 0x3b,
        Key::F2 => 0x3c,
        Key::F3 => 0x3d,
        Key::F4 => 0x3e,
        Key::F5 => 0x3f,
        Key::F6 => 0x40,
        Key::F7 => 0x41,
        Key::F8 => 0x42,
        Key::F9 => 0x43,
        Key::F10 => 0x44,
        Key::NumLock => 0x45,
        Key::ScrollLock => 0x46,
        Key::NumPad7 => 0x47,
        Key::NumPad8 => 0x48,
        Key::NumPad9 => 0x49,
        Key::NumPadMinus => 0x4a,
        Key::NumPad4 => 0x4b,
        Key::NumPad5 => 0x4c,
        Key::NumPad6 => 0x4d,
        Key::NumPadPlus => 0x4e,
        Key::NumPad1 => 0x4f,
        Key::NumPad2 => 0x50,
        Key::NumPad3 => 0x51,
        Key::NumPad0 => 0x52,
        Key::NumPadDot => 0x53,
        Key::F11 => 0x57,
        Key::F12 => 0x58,
        Key::NumPadEnter => 0x9c,
        Key::RightCtrl => 0x9d,
        Key::NumPadSlash => 0xb5,
        Key::RightAlt => 0xb8,
        Key::Home => 0xc7,
        Key::Up => 0xc8,
        Key::PageUp => 0xc9,
        Key::Left => 0xcb,
        Key::Right => 0xcd,
        Key::End => 0xcf,
        Key::Down => 0xd0,
        Key::PageDown => 0xd1,
        Key::Insert => 0xd2,
        Key::Delete => 0xd3,
        Key::LeftSuper => 0xdb,
        Key::RightSuper => 0xdc,
        Key::Menu => 0xdd,
        _ => 0,
    }
}
